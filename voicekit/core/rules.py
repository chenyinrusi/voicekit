def by_layer(layer: str) -> list[dict]:
    return [rule for rule in RULES if rule["layer"] == layer]


def markers(rule: dict) -> list[str]:
    """这条规矩的判词（字符串或列表都接受）。"""
    value = rule.get("check") or []
    return [value] if isinstance(value, str) else list(value)


#: 整张表的下次复查日（不是每条各写一个：规矩是一起看的，退休也是整表讨论）。
#: 到期后每次改稿都在报告「黄」栏提一句，逼着人看一眼哪些该退、哪些该改。
REVIEW_BY = date(2027, 2, 10)


def review_due(today: date | None = None) -> bool:
    return (today or date.today()) >= REVIEW_BY

